def create_owned_dialogue_candidate(
    blueprint_path: Path = DEFAULT_BLUEPRINT_PATH,
    candidate_path: Path = DEFAULT_CANDIDATE_PATH,
    report_directory: Path = DEFAULT_REPORT_DIRECTORY,
    *,
    staging_root: Path = DEFAULT_STAGING_ROOT,
    results_root: Path = RESULTS_ROOT,
) -> dict[str, Any]:
    """Создаёт atomically один immutable staging candidate и safe creation report."""
    blueprint = _load_blueprint(blueprint_path, results_root)
    destination = _safe_candidate_path(candidate_path, staging_root)
    report_destination = _safe_report_directory(report_directory, results_root)
    records = build_owned_dialogue_records(blueprint)
    quality = assess_owned_dialogue_records(records, blueprint)

    with tempfile.NamedTemporaryFile(
        mode="w",
        encoding="utf-8",
        newline="\n",
        dir=destination.parent,
        prefix=".brain-v3-owned-dialogues-",
        suffix=".tmp",
        delete=False,
    ) as temporary_file:
        temporary_path = Path(temporary_file.name)
        try:
            for record in records:
                temporary_file.write(json.dumps(record, ensure_ascii=False, separators=(",", ":")))
                temporary_file.write("\n")
            temporary_file.flush()
        except BaseException:
            temporary_file.close()
            temporary_path.unlink(missing_ok=True)
            raise
    try:
        temporary_path.replace(destination)
    except BaseException:
        temporary_path.unlink(missing_ok=True)
        raise

    summary = {
        "format_version": 1,
        "mode": "owned_dialogue_staging_creation",
        "source_id": SOURCE_ID,
        "source_kind": SOURCE_KIND,
        "license": SOURCE_LICENSE,
        "candidate_path": str(destination),
        "candidate_sha256": file_sha256(destination),
        "candidate_bytes": destination.stat().st_size,
        "quality": quality,
        "candidate_is_active": False,
        "active_manifest_updated": False,
        "training_started": False,
        "github_changed": False,
    }
    try:
        with tempfile.TemporaryDirectory(
            dir=report_destination.parent,
            prefix=".brain-v3-owned-dialogues-report-",
        ) as temporary_directory:
            temporary_report = Path(temporary_directory)
            (temporary_report / "owned_dialogue_creation.json").write_text(
                json.dumps(summary, ensure_ascii=False, indent=2),
                encoding="utf-8",
            )
            (temporary_report / "OWNED_DIALOGUE_CREATION_REPORT.md").write_text(
                creation_summary_markdown(summary),
                encoding="utf-8",
            )
            temporary_report.replace(report_destination)
    except BaseException:
        # Candidate остаётся immutable evidence creation. Отчётный сбой не
        # выдаётся за успешную promotion и не трогает active corpus.
        raise
    return summary


def main() -> None:
    """Создаёт fixed local v0.7 candidate без network, API, training и GitHub."""
    try:
        summary = create_owned_dialogue_candidate()
    except (OwnedDialogueError, OSError, ValueError) as error:
        raise SystemExit(f"Project-owned dialogue candidate остановлен: {error}") from error
    print(json.dumps(summary, ensure_ascii=True, indent=2))


if __name__ == "__main__":
    main()
