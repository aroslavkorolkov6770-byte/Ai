const {fs,path,lab,root}=require('./lab_client.cjs');
async function latest(prefix){
    const files=(await fs.readdir(lab)).filter(x=>x.startsWith(prefix)&&x.endsWith('.json')).sort();
    if(!files.length)throw new Error('Missing evidence: '+prefix);
    return {file:files.at(-1),data:JSON.parse(await fs.readFile(path.join(lab,files.at(-1)),'utf8'))};
}
