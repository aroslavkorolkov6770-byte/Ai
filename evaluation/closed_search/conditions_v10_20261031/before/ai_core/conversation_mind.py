def _dialogue_focus(prompt: str, messages: list[dict[str, Any]]) -> str | None:
    """Находит только общий тип ситуации в текущей короткой истории.

    Результат намеренно состоит из закрытого списка категорий. Он нужен, чтобы
    выбрать собственную полезную формулировку, а не сделать вывод о личности
    пользователя или сохранить его частные детали как факт.
    """
    recent_user_text = " ".join(_previous_user_messages(messages)[-2:])
    phrase = _normalise(f"{recent_user_text} {prompt}")
    if any(marker in phrase for marker in ("ссор", "конфликт", "поруг", "обид")):
        return "conflict"
    if any(marker in phrase for marker in ("тревож", "волнуюсь", "пережива", "страшно", "боюсь")):
        return "anxiety"
    if any(marker in phrase for marker in (
        "устал", "перегруз", "работ", "учеб", "дел много", "не успева",
        "времени мало", "нагруз",
    )):
        return "overload"
    if any(marker in phrase for marker in (
        "выбрать", "выбор", "вариант", "решени", "между", "стоит ли",
    )):
        return "choice"
    if any(marker in phrase for marker in (
        "друг", "подруг", "родител", "партн", "близк", "отношен",
    )):
        return "relationship"
    return None


def _contextual_detail(
    intent: str,
    prompt: str,
    messages: list[dict[str, Any]],
    salt: str,
) -> str | None:
    """Возвращает одну подходящую деталь из закрытого редакторского набора."""
    focus = _dialogue_focus(prompt, messages)
    details = _CONTEXTUAL_DETAILS.get(intent, {}).get(focus or "")
    if not details:
        return None
    index = _stable_number(salt, f"contextual-detail:{intent}:{focus}") % len(details)
    return details[index]


def response_pool_size() -> int:
    """Возвращает число доступных базовых комбинаций без учёта темы и истории."""
    return sum(
        len(_OPENINGS[intent]) * len(_MIDDLES.get(intent, ("",))) * len(_CLOSERS[intent])
        for intent in _OPENINGS
    )


def _candidate_text(
    intent: str,
    prompt: str,
    messages: list[dict[str, Any]],
    conversation_id: str,
    attempt: int,
) -> str:
    """Собирает один вариант ответа и не использует непроверенный текст архива."""
    topic = _topic_from_text(prompt)
    prior_topics = [_topic_from_text(text) for text in _previous_user_messages(messages)]
    prior_topic = next((item for item in reversed(prior_topics) if item), None)
    verbosity = _verbosity(prompt, intent, messages)
    salt = f"{conversation_id}|{_normalise(prompt)}|{prior_topic or ''}|{intent}|{attempt}"

    def select(values: tuple[str, ...], name: str) -> str:
        return values[_stable_number(salt, name) % len(values)]

    opening = select(_OPENINGS[intent], "opening")
    middle = select(_MIDDLES.get(intent, ("",)), "middle")
    closer = select(_CLOSERS[intent], "closer")
    contextual_detail = _contextual_detail(intent, prompt, messages, salt)
    if contextual_detail:
        # Для распознанной ситуации одна конкретная мысль полезнее двух
        # обобщений подряд. Деталь заменяет среднюю фразу, сохраняя короткую
        # и читаемую структуру ответа.
        middle = contextual_detail
    topic_line = ""
    if intent in {"conversation", "opinion", "choice"}:
        chosen_topic = topic or prior_topic
        if chosen_topic:
            topic_forms = (
                f"Сфокусируемся на теме «{chosen_topic}».",
                f"В этой части разговора важна тема «{chosen_topic}».",
                f"Держу в фокусе: «{chosen_topic}».",
                f"Можно оттолкнуться от темы «{chosen_topic}».",
            )
            topic_line = select(topic_forms, "topic")

    sentences = [opening]
    if verbosity != "short" or intent in {
        "support", "advice", "choice", "continuation", "correction", "clarify", "guide",
    }:
        if middle:
            sentences.append(middle)
    if topic_line and verbosity != "short":
        sentences.append(topic_line)
    if closer:
        sentences.append(closer)
    return " ".join(sentence.strip() for sentence in sentences if sentence.strip())


def compose_conversation_reply(
    intent: str,
    prompt: str,
    messages: list[dict[str, Any]],
    conversation_id: str,
    confidence: float,
) -> ConversationMindReply:
    """Подбирает неповторяющийся вариант, используя последние ответы как стоп-лист."""
    if intent not in _OPENINGS:
        raise ValueError(f"Неизвестный intent conversation-mind: {intent}")
    previous = _previous_assistant_texts(messages)
    selected = ""
    for attempt in range(64):
        candidate = _candidate_text(intent, prompt, messages, conversation_id, attempt)
        if _normalise(candidate) not in previous:
            selected = candidate
            break
    if not selected:
        # Теоретически возможен только при очень длинной одинаковой истории.
        # Этот вариант остаётся связанным с intent и не обращается к генератору.
        selected = _candidate_text(intent, prompt, messages, conversation_id, 65)
    return ConversationMindReply(
        text=selected,
        intent=intent,
        confidence=confidence,
        context_used=bool(_previous_user_messages(messages)),
        verbosity=_verbosity(prompt, intent, messages),
    )


class ConversationMind:
    """Локальная сеть планов ответа и безопасный разнообразный композитор."""

    def __init__(self, checkpoint: dict[str, Any]) -> None:
        if checkpoint.get("format_version") != FORMAT_VERSION:
            raise ValueError("Неизвестный формат checkpoint conversation-mind.")
        labels = tuple(checkpoint.get("labels", ()))
        if labels != LABELS:
            raise ValueError("Conversation-mind содержит неизвестный порядок планов.")
        version = checkpoint.get("model_version")
        if not isinstance(version, str) or not version.strip():
            raise ValueError("В checkpoint conversation-mind отсутствует версия.")
        thresholds = checkpoint.get("thresholds")
        if not isinstance(thresholds, dict):
            raise ValueError("В checkpoint conversation-mind отсутствуют пороги.")
        confidence = thresholds.get("intent_confidence")
        margin = thresholds.get("minimum_margin")
        coverage = thresholds.get("minimum_coverage")
        for name, value in (
            ("intent_confidence", confidence),
            ("minimum_margin", margin),
            ("minimum_coverage", coverage),
        ):
            if not isinstance(value, int | float) or not 0.0 <= float(value) <= 1.0:
                raise ValueError(f"Некорректный порог {name} conversation-mind.")
        if float(confidence) < 0.35:
            raise ValueError("Порог intent_confidence conversation-mind слишком низкий.")
        model_config = checkpoint.get("model_config")
        if not isinstance(model_config, dict) or model_config.get("classes") != len(LABELS):
            raise ValueError("Некорректная конфигурация conversation-mind.")

        self.version = version.strip()
        self.labels = labels
        self.thresholds = {
            "intent_confidence": float(confidence),
            "minimum_margin": float(margin),
            "minimum_coverage": float(coverage),
        }
        self.encoder = RouterFeatureEncoder(
            checkpoint["vocabulary"],
            checkpoint["idf"],
            checkpoint.get("feature_stopwords"),
        )
        self.network = RouterNetwork(**model_config)
        self.network.load_state_dict(checkpoint["model_state"])
        self.network.eval()

    @classmethod
    def load(
        cls,
        path: Path = DEFAULT_CONVERSATION_MIND_ARTIFACT,
    ) -> "ConversationMind":
        """Загружает только локальные веса без готовой внешней языковой модели."""
        return cls(torch.load(path, map_location="cpu", weights_only=True))

    def predict(self, prompt: str) -> ConversationMindPrediction:
        """Классифицирует устойчивый план разговора с сохранёнными порогами."""
        clean_prompt = prompt.strip() if isinstance(prompt, str) else ""
        if not clean_prompt:
            return ConversationMindPrediction("CLARIFY", 0.0, 0.0, 0.0, False)
        indices, offsets, weights, coverage = self.encoder.encode_batch([clean_prompt])
        with torch.inference_mode():
            probabilities = self.network(indices, offsets, weights).softmax(dim=-1)[0]
        values, indices_by_probability = torch.topk(probabilities, k=2)
        plan = self.labels[int(indices_by_probability[0])]
        confidence = float(values[0])
        margin = float(values[0] - values[1])
        accepted = (
            confidence >= self.thresholds["intent_confidence"]
            and margin >= self.thresholds["minimum_margin"]
            and coverage[0] >= self.thresholds["minimum_coverage"]
        )
        return ConversationMindPrediction(plan, confidence, margin, coverage[0], accepted)

    def reply(
        self,
        prompt: str,
        messages: list[dict[str, Any]],
        conversation_id: str,
    ) -> ConversationMindReply | None:
        """Отвечает только на человеческое общение, не заменяя поиск фактов."""
        clean_prompt = prompt.strip() if isinstance(prompt, str) else ""
        if not clean_prompt:
            return None
        direct_intent = _explicit_intent(clean_prompt)
        if _should_defer_to_knowledge(clean_prompt, direct_intent):
            return None
        if direct_intent == "safety_support":
            return ConversationMindReply(
                text=_SAFETY_SUPPORT_REPLY,
                intent="safety_support",
                confidence=1.0,
                context_used=bool(_previous_user_messages(messages)),
                verbosity="extended",
            )
        if direct_intent is not None:
            return compose_conversation_reply(
                direct_intent,
                clean_prompt,
                messages,
                conversation_id,
                confidence=1.0,
            )
        prediction = self.predict(clean_prompt)
        if not prediction.accepted:
            return None
        return compose_conversation_reply(
            _PLAN_TO_INTENT[prediction.plan],
            clean_prompt,
            messages,
            conversation_id,
            confidence=prediction.confidence,
        )
