def _normalise(value: str) -> str:
    """Нормализует текст для сравнения вариантов без изменения ответа."""
    return _SPACE.sub(" ", value.casefold()).strip()


def _stable_number(*parts: str) -> int:
    """Создаёт воспроизводимый выбор варианта без глобального random-состояния."""
    payload = "\u0000".join(parts).encode("utf-8")
    return int.from_bytes(hashlib.sha256(payload).digest()[:8], "big")


def _previous_user_messages(messages: list[dict[str, Any]]) -> list[str]:
    """Берёт только собственные слова пользователя, не считая ответ фактами."""
    return [
        str(message["content"]).strip()
        for message in messages
        if message.get("role") == "user"
        and isinstance(message.get("content"), str)
        and message["content"].strip()
    ]


def _previous_assistant_texts(messages: list[dict[str, Any]]) -> set[str]:
    """Собирает недавние ответы, которые нельзя повторить дословно."""
    return {
        _normalise(str(message["content"]))
        for message in messages
        if message.get("role") == "assistant"
        and isinstance(message.get("content"), str)
        and message["content"].strip()
    }


def _topic_from_text(text: str) -> str | None:
    """Выделяет короткую безопасную тему без копирования полной реплики."""
    words = [
        word.casefold()
        for word in _WORD.findall(text)
        if len(word) >= 4 and word.casefold() not in _TOPIC_STOPWORDS
    ]
    if not words:
        return None
    # Последние смысловые слова обычно ближе к предмету реплики. Ограничение
    # тремя словами не позволяет случайно процитировать большой текст пользователя.
    return " ".join(words[-3:])


def _explicit_intent(clean_prompt: str) -> str | None:
    """Распознаёт редкие, но очевидные человеческие реплики до сети."""
    phrase = normalize_route_text(clean_prompt)
    if not phrase:
        return None
    if any(marker in phrase for marker in _SAFETY_SUPPORT_MARKERS):
        return "safety_support"
    if phrase in {"привет", "здравствуй", "здравствуйте", "приветик", "хай"}:
        return "greeting"
    # Небольшой дружеский вопрос после приветствия — всё ещё начало обычного
    # разговора, а не повод отдавать старый учебный ответ из QA-каталога.
    # Регулярное выражение намеренно узкое: «Привет, как сделать…» не будет
    # ошибочно принято за приветствие и продолжит обычную маршрутизацию.
    if re.fullmatch(
        r"(?:привет|здравствуй|здравствуйте|приветик|хай)\s+(?:"
        r"как\s+(?:ты|дела)(?:\s+у\s+тебя)?|"
        r"что\s+нового\s+у\s+тебя"
        r")",
        phrase,
    ):
        return "greeting"
    if phrase.startswith(("доброе утро", "добрый день", "добрый вечер")):
        return "greeting"
    if phrase.startswith(("спасибо", "благодарю", "спс", "благодарочка")):
        return "gratitude"
    if phrase in {
        "пока", "пока пока", "пока-пока", "до свидания", "до встречи",
        "до связи", "до скорого", "увидимся", "увидимся позже", "бывай",
        "всего доброго", "хорошего вечера",
    }:
        return "farewell"
    if phrase.startswith((
        "ты не понял", "не так", "неправильно", "я имел в виду", "я имела в виду",
        "я хотел", "я хотела", "передумал", "передумала",
    )):
        return "correction"
    if any(marker in phrase for marker in (
        "мне грустно", "мне плохо", "мне тяжело", "мне тревожно", "мне одиноко",
        "мне страшно", "я тревожусь", "я волнуюсь", "я переживаю", "я боюсь",
        "не знаю что делать", "не понимаю что делать", "все испортил", "всё испортил",
        "ничего не получится", "совсем плохо", "мне сложно", "я расстроен",
        "я расстроена", "все валится", "всё валится", "хочу выговориться",
        "можешь выслушать", "выслушай меня", "поссорился", "поссорилась",
        "меня бросили", "мне отказали",
    )) or re.search(r"\bустал(?:а)?\b", phrase):
        return "support"
    if phrase.startswith((
        "как дела", "что нового у тебя", "поговорим", "давай поговорим",
        "поговори со мной", "давай поболтаем", "можно просто поговорить",
        "я просто хотел поговорить", "я просто хотела поговорить",
    )) or any(marker in phrase for marker in (
        "хочу обсудить", "давай обсудим", "обсудим вместе", "хочу поговорить",
    )):
        return "conversation"
    if phrase.startswith((
        "что ты думаешь", "как ты считаешь", "твое мнение", "твоё мнение",
        "мне кажется", "я думаю",
    )):
        return "opinion"
    if any(marker in phrase for marker in (
        "помоги выбрать", "не могу выбрать", "нужно выбрать", "надо выбрать",
        "выбрать между", "что выбрать", "какой вариант выбрать", "посоветуй мне",
        "стоит ли мне",
    )):
        return "choice"
    if any(marker in phrase for marker in (
        "как мне поступить", "как мне поговорить", "как мне сказать",
        "что мне делать", "дай совет", "посоветуй", "помоги разобраться",
        "мне нужен совет", "как организовать", "помоги спланировать",
        "составить план",
    )) or re.search(
        r"\bкак\s+мне(?:\s+[a-zа-яё]+){0,3}\s+(?:поговорить|сказать|поступить)\b",
        phrase,
        flags=re.IGNORECASE,
    ):
        return "advice"
    if phrase.startswith((
        "у меня получилось", "я смог", "я смогла", "я закончил", "я закончила",
        "я сдал", "я сдала", "я получил", "я получила", "я справился",
        "я справилась",
    )) or any(marker in phrase for marker in (
        "я рад", "я рада", "я горжусь собой", "у меня вышло",
    )):
        return "celebration"
    if phrase.startswith(("расскажи шутку", "придумай", "давай придумаем", "давай сочиним")):
        return "creative"
    if phrase.startswith(("я не согласен", "я не согласна", "не соглашусь", "мне кажется иначе")):
        return "disagreement"
    if any(marker in phrase for marker in (
        "я предпочитаю", "мне важно", "я люблю", "я не люблю", "мне нравится",
        "мне не нравится",
    )):
        return "preference"
    if phrase.startswith(("продолжим", "давай дальше", "а дальше", "и что дальше")):
        return "continuation"
    if phrase.startswith((
        "я не понял", "я не поняла", "не понимаю", "что ты имеешь в виду",
        "что это значит",
    )):
        return "clarify"
    return None


def _should_defer_to_knowledge(clean_prompt: str, explicit_intent: str | None) -> bool:
    """Не даёт разговорному слою подменить факт, интернет или погоду."""
    phrase = _normalise(clean_prompt)
    # Это признаки, при которых даже дружеская формулировка должна перейти к
    # погоде или поиску: «как ты думаешь, какая погода?» всё равно требует
    # проверяемого прогноза, а не разговорного ответа.
    strict_external_markers = (
        "найди", "поищи", "в интернете", "в сети", "на сайте", "проверь",
        "актуальн", "свеж", "новост", "погода", "курс валют", "цена",
        "стоим", "расписан",
    )
    if explicit_intent is not None:
        # «Привет, сколько сейчас времени?» — это всё-таки запрос факта. Но
        # «Я сегодня устал» и «как ты считаешь, стоит ли мне сегодня…»
        # остаются разговорными репликами. Относительное время само по себе
        # не должно отменять очевидный человеческий intent.
        direct_fact_markers = (
            "найди", "поищи", "в интернете", "в сети", "на сайте", "проверь",
            "актуальн", "свеж", "новост", "погода", "курс валют", "цена",
            "стоим", "расписан",
        )
        if _EMBEDDED_TEMPORAL_FACT.search(phrase) or any(
            marker in phrase for marker in direct_fact_markers
        ):
            return True
        return False
    if any(marker in phrase for marker in strict_external_markers):
        return True
    if any(marker in phrase for marker in _EXTERNAL_MARKERS):
        return True
    return bool(_FACTUAL_PREFIX.search(phrase))


def _dialogue_length_preference(messages: list[dict[str, Any]]) -> str | None:
    """Находит явную просьбу о длине ответа только в текущем диалоге.

    Выбор не записывается отдельно и не действует в новом conversation_id.
    Обратный обход нужен, чтобы последнее явно названное пожелание всегда
    отменяло более раннее.
    """
    for message in reversed(_previous_user_messages(messages)):
        phrase = _normalise(message)
        if any(marker in phrase for marker in (
            "не отвечай коротко", "не пиши коротко", "не нужны короткие",
            "не нравятся короткие", "хочу подробные", "нужны подробные",
            "подробные ответы", "отвечай подробнее", "пиши подробно",
            "развернутые ответы", "развёрнутые ответы",
        )):
            return "extended"
        if any(marker in phrase for marker in (
            "ответы были короткими", "короткие ответы", "отвечай кратко",
            "отвечай коротко", "пиши короче", "без воды", "по делу",
            "краткие ответы",
        )):
            return "short"
    return None


def _verbosity(
    prompt: str,
    intent: str,
    messages: list[dict[str, Any]],
) -> str:
    """Выбирает компактный ответ по умолчанию и развёрнутый при необходимости."""
    clean = _normalise(prompt)
    if intent in {"support", "safety_support"}:
        return "extended"
    if any(marker in clean for marker in ("подробнее", "детально", "развернуто", "развёрнуто", "по шагам")):
        return "extended"
    preference = _dialogue_length_preference(messages)
    if preference is not None:
        return preference
    if intent in {
        "advice", "choice", "continuation", "correction", "disagreement",
        "clarify", "guide", "relationship",
    } or len(clean) > 150:
        return "balanced"
    return "short"


