async function latest(prefix){
    const files=(await fs.readdir(lab)).filter(name=>name.startsWith(prefix)&&name.endsWith('.json')).sort();
    if(!files.length)throw new Error('Missing evidence: '+prefix);
    const file=files.at(-1);
    return {file,data:JSON.parse(await fs.readFile(path.join(lab,file),'utf8'))};
}
